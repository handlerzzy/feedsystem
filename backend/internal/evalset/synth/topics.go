// 本文件是话题词表。
//
// 为什么把词表写成静态字面量而不是"随机生成中文串"：
// 词表就是这份数据里**唯一的语义信号**。随机串之间没有任何语义关系，
// 用它们生成的评测集同样无法区分"语义召回"与"随机排序"——
// 那就又回到了 B2 要修的那个退化问题上，只是换了个形式。
//
// 每个话题的 TitleTerms 之间词面几乎不重叠，且刻意区分了
//   - 技术类：中英混排（goroutine / channel / 索引 / 缓存）
//   - 生活类：纯中文多字词
//
// 这样字符 bigram 词法模型与真实 embedding 都能把它们分开。
type topic struct {
	// Name 是话题名，会出现在标题里。
	Name string
	// TitleTerms 是标题词，每条视频随机取两个。
	TitleTerms []string
	// DescLines 是描述句片段，每条视频随机取 2~3 句拼接。
	DescLines []string
}

// title 生成一条标题。
//
// 用三种句式轮换，避免"所有标题长得一模一样"：句式完全一致时，
// 区分度全部来自词表本身，词法模型的成绩会虚高（模板也是特征）。
// 真实数据里模板噪声是存在的，这里保留一点。
func (t topic) title(rnd *rand.Rand) string {
	a := t.TitleTerms[rnd.Intn(len(t.TitleTerms))]
	b := t.TitleTerms[rnd.Intn(len(t.TitleTerms))]
	for b == a && len(t.TitleTerms) > 1 {
		b = t.TitleTerms[rnd.Intn(len(t.TitleTerms))]
	}
	switch rnd.Intn(3) {
	case 0:
		return fmt.Sprintf("%s实战：%s与%s", t.Name, a, b)
	case 1:
		return fmt.Sprintf("%s入门到上手：%s怎么用", t.Name, a)
	default:
		return fmt.Sprintf("聊聊%s：%s踩过的坑", t.Name, b)
	}
}

// description 生成一条描述（2~3 句）。
func (t topic) description(rnd *rand.Rand) string {
	n := 2 + rnd.Intn(2)
	if n > len(t.DescLines) {
		n = len(t.DescLines)
	}
	picked := rnd.Perm(len(t.DescLines))[:n]
	out := ""
	for i, idx := range picked {
		if i > 0 {
			out += "。"
		}
		out += t.DescLines[idx]
	}
	return out + "。"
}

